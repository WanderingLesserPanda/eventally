-- +goose Up
-- 000007_recurring_fix: make month-start generation race-safe and give
-- transactions their source-of-origin back-references (schema rework, Gate 2;
-- feedback items #6 + #7).
--
-- The old generation relied only on recurring_template.last_generated_date as
-- a pre-check. Two workers loading the recurring page at the same time both
-- see last_generated_date < monthStart and BOTH insert this month's entry.
-- The fix is three layers, each one load-bearing:
--   1. a row lock (SELECT ... FOR UPDATE on the template) serializes workers;
--   2. a back-reference column (transaction.recurring_template_id) links each
--      generated row to the template that made it;
--   3. a void-aware unique index on (template, date) is the actual guarantee —
--      even if the lock is bypassed, the second INSERT hits 23505 and is
--      skipped. Voided rows are excluded, so a voided month regenerates.

-- (a) Back-reference + import idempotency on transaction.
ALTER TABLE "transaction"
    ADD COLUMN recurring_template_id BIGINT
        REFERENCES recurring_template(id) ON DELETE SET NULL;
-- Rows generated by the month-start job point at their template.
CREATE INDEX idx_txn_recurring ON "transaction" (recurring_template_id);
-- external_source_id: the import row id, so a re-import of the same file
-- dedupes instead of double-recording. Populated by the next import run.
ALTER TABLE "transaction" ADD COLUMN external_source_id TEXT;
CREATE UNIQUE INDEX uq_txn_external_source
    ON "transaction" (external_source_id)
    WHERE external_source_id IS NOT NULL;

-- (b) Void-aware uniqueness: at most ONE live (non-void) occurrence per
--     template per date. This is the concurrency guarantee.
CREATE UNIQUE INDEX uq_txn_recurring_occurrence
    ON "transaction" (recurring_template_id, transaction_date)
    WHERE recurring_template_id IS NOT NULL AND record_status <> 'void';

-- (c) split_spec: the ';'-separated TEXT list becomes a JSONB array of
--     participant keys, e.g. ["user:3","cp:2"]. Lossless: split on ';',
--     trim, drop empties. (The participant key format itself is unchanged —
--     it only becomes the array elements.)
-- Postgres forbids subqueries in a TYPE ... USING transform, so the
-- conversion runs through a helper function (IMMUTABLE, kept for the Down
-- direction and for ad-hoc back-conversion).
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION text_keys_to_jsonb(s TEXT) RETURNS JSONB AS $$
DECLARE
    out JSONB := '[]'::jsonb;
    k TEXT;
BEGIN
    IF s IS NOT NULL AND trim(s) <> '' THEN
        FOREACH k IN ARRAY string_to_array(trim(s), ';') LOOP
            k := trim(k);
            IF k <> '' THEN
                out := out || to_jsonb(k);
            END IF;
        END LOOP;
    END IF;
    RETURN out;
END;
$$ LANGUAGE plpgsql IMMUTABLE;
-- +goose StatementEnd
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION jsonb_keys_to_text(j JSONB) RETURNS TEXT AS $$
SELECT COALESCE(string_agg(k, ';'), '')
FROM jsonb_array_elements_text(j) AS k;
$$ LANGUAGE sql IMMUTABLE;
-- +goose StatementEnd
-- The column carries a TEXT default ('' from 000003) that cannot
-- auto-cast to JSONB, so it must be dropped before the type change.
ALTER TABLE recurring_template ALTER COLUMN split_spec DROP DEFAULT;
ALTER TABLE recurring_template
    ALTER COLUMN split_spec TYPE JSONB
    USING text_keys_to_jsonb(split_spec);
ALTER TABLE recurring_template ALTER COLUMN split_spec SET DEFAULT '[]'::jsonb;

-- (d) One settlement per ledger transaction (the app already guarantees it;
--     make it a DB invariant). NULLs (settlements that don't move money in
--     the ledger) stay allowed — Postgres UNIQUE treats NULLs as distinct.
ALTER TABLE payment
    ADD CONSTRAINT uq_payment_ledger_txn UNIQUE (ledger_transaction_id);

